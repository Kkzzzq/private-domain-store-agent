const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {execFileSync} = require('node:child_process');
const properties = new Map();
const context = vm.createContext({document: {documentElement: {style: {setProperty: (key, value) => properties.set(key, value)}}}});
vm.runInContext(fs.readFileSync('web/app.js', 'utf8'), context);
const python = path.resolve('backend/.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
const backendDefaults = JSON.parse(execFileSync(python, ['-c', 'from app.schemas.storefront import StorefrontSettings; print(StorefrontSettings().model_dump_json())'], {cwd: path.resolve('backend'), encoding: 'utf8'}));
assert.deepEqual(JSON.parse(JSON.stringify(context.storefrontSettings({}))), backendDefaults);
const shop = {storefront: {background_color: '#eeddcc', surface_color: '#fff5e8', rail_columns: '4', product_image_ratio: '3/4', free_shipping_yuan: 200, base_freight_yuan: 15}};
context.applyStorefrontSettings(shop);
assert.equal(properties.get('--store-background'), '#eeddcc');
assert.equal(properties.get('--store-card-ratio'), '3/4');
assert.equal(properties.get('--store-rail-columns'), '4');
assert.equal(context.storeFreight(shop, 199.99), 15);
assert.equal(context.storeFreight(shop, 200), 0);
assert.equal(context.storeFreight(shop, 0), 0);
assert.ok(context.storeShippingText(shop).includes('200'));
assert.equal(context.storeShippingText({storefront: {free_shipping_yuan: 0}}), '全店包邮');
console.log('B/C defaults, CSS config and shipping calculation checks passed');
