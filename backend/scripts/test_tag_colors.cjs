const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const context = vm.createContext({});
vm.runInContext(fs.readFileSync("web/app.js", "utf8"), context);
const properties = new Map();
const node = {style: {setProperty: (key, value) => properties.set(key, value), removeProperty: key => properties.delete(key)}};
context.applyTagStyle(node, {background_color: "#faf1de", border_color: "#e0be8a", text_color: "#60411a"});
assert.equal(properties.get("--tag-background"), "#faf1de");
assert.equal(properties.get("--tag-border"), "#e0be8a");
assert.equal(properties.get("--tag-text"), "#60411a");
context.applyTagStyle(node, {color: "#ff5000", text_color: "red;display:none"});
assert.equal(properties.size, 1);
assert.equal(properties.get("--tag"), "#ff5000");
const defaults = context.tagColorDefaults({color: "#ff5000"});
assert.equal(defaults.background_color, "#fff1eb");
assert.equal(defaults.border_color, "#ffd5c2");
assert.equal(context.tagColorDefaults({text_color: "#123456"}).text_color, "#123456");
console.log("Tag colors: independent values, legacy defaults, invalid CSS rejection and stale-style clearing passed");
